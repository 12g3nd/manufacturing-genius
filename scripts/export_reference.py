"""Export checked toy-game results for later browser cross-checks; no simulation data."""
from dataclasses import asdict
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from manufacturing_genius import duel_payoff_matrix, zero_sum_equilibrium


def build_reference():
    scenarios = []
    # Every reachable slider combination, plus zero-risk and off-grid states.
    for size, gaps in ((10.0, list(range(-25, 26)) + [-10.001, -9.999, .001, 9.999, 10.001]),
                       (0.0, [-1, 0, 1]), (.5, [-1, -.5, -.1, 0, .1, .5, 1])):
        for gap in gaps:
            for correlation in (i / 10 for i in range(-10, 11)):
                parameters = {"initial_gap": gap, "shock_size": size, "correlation": correlation}
                matrix = duel_payoff_matrix(**parameters)
                equilibrium = zero_sum_equilibrium(matrix)
                scenarios.append({"parameters": parameters, "payoff_matrix": matrix,
                                  "equilibrium": asdict(equilibrium)})
    return {
        "kind": "exact_illustrative_model",
        "units": "points and expected prize shares",
        "action_order": ["safe", "risky"],
        "rows": "player_a",
        "columns": "player_b",
        "tie_rule": "half the prize to each player",
        "provenance": "Generated by scripts/export_reference.py from the checked Python core.",
        "scenarios": scenarios,
    }


if __name__ == "__main__":
    destination = ROOT / "data" / "reference" / "duel_benchmark.json"
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(json.dumps(build_reference(), indent=2, allow_nan=False) + "\n", encoding="utf-8")
    print(destination.relative_to(ROOT))
